/**
 * Fisher-Yates shuffle helper
 */
export function shuffleArray(array) {
  const arr = [...array];
  for (let i = arr.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [arr[i], arr[j]] = [arr[j], arr[i]];
  }
  return arr;
}

/**
 * Generate randomized session question bank
 */
export function generateSessionQuestions() {
  // Shuffle questions within each world while maintaining world structure
  const result = [];
  for (let w = 0; w < 10; w++) {
    const worldQs = RAW_QUESTION_BANK.filter(q => q.world === w);
    const shuffledWorld = shuffleArray(worldQs);
    // Shuffle options for each question
    const processedQs = shuffledWorld.map(q => {
      if (q.options) {
        return {
          ...q,
          options: shuffleArray(q.options)
        };
      }
      return q;
    });
    result.push(...processedQs);
  }
  return result;
}
